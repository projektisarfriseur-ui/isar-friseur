export function useAdminT() {
  const { lang, setLang } = useLang();
  const L = lang === 'en' ? 'en' : 'de';
  const t = (key, vars) => {
    let s = DICT[L][key] ?? DICT.de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
  return { lang: L, setLang, t, locale: L === 'en' ? 'en-GB' : 'de-DE' };
}

// Small DE | EN toggle used in the admin header and on the login pages.
export function LangToggle({ style }) {
  const { lang, setLang, t } = useAdminT();
  const btn = (code) => (
    <button key={code} type="button" onClick={() => setLang(code)} aria-pressed={lang === code}
      style={{
        background: 'transparent', border: 0, cursor: 'pointer', minWidth: 36, minHeight: 44, padding: '0 6px',
        fontFamily: 'var(--font-body)', fontSize: 12, fontWeight: 600, letterSpacing: '0.16em',
        color: lang === code ? 'var(--ghg-copper)' : 'var(--fg-2)',
      }}>{code.toUpperCase()}</button>
  );
  return (
    <div role="group" aria-label={t('common.langSwitch')} style={{ display: 'inline-flex', alignItems: 'center', ...style }}>
      {btn('de')}<span aria-hidden="true" style={{ color: 'var(--fg-3)' }}>|</span>{btn('en')}
    </div>
  );
}
